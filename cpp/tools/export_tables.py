#!/usr/bin/env python3
"""Generates the data files the C++ core needs from the Python reference implementation:
  src/gadget_tables.inc   (perm, Z8 phase) tables of every gadget on its local qubits: {name, k, cost, perm[2^k], phase[2^k]},
  data/db3.tab            three-qubit permutation database: one line "p0 ... p7 cost" per permutation with a known cost.
Run from the repository root: python cpp/tools/export_tables.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE)); sys.path.insert(0, ROOT)
from toffoli_optimizer.core import resynth as RS, template as TP


def main():
    rows = []
    for nm, (cost, fn) in RS._local_gadgets().items():
        p, f = RS._tablesk(fn, 3); rows.append((nm, 3, cost, p, f))
    for nm, (cost, k, fn) in RS._parity_gadgets().items():
        p, f = RS._tablesk(fn, k); rows.append((nm, k, cost, p, f))
    with open(os.path.join(HERE, "..", "src", "gadget_tables.inc"), "w") as o:
        o.write("// generated by cpp/tools/export_tables.py - do not edit\n")
        for nm, k, cost, p, f in rows:
            o.write('{"%s", %d, %d, {%s}, {%s}},\n' % (nm, k, cost, ",".join(str(int(v)) for v in p), ",".join(str(int(v)) for v in f)))
    db = TP.load_db3(os.path.join(ROOT, "toffoli_optimizer", "core", "db3_costs.json"))
    with open(os.path.join(HERE, "..", "data", "db3.tab"), "w") as o:
        for perm, (cost, ci) in sorted(db.items()): o.write(" ".join(map(str, perm)) + " %d\n" % cost)
    print(len(rows), "gadgets,", len(db), "database permutations")


if __name__ == "__main__": main()
